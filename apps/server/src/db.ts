import path from "path";
import { fileURLToPath } from "url";
import { migrate } from "drizzle-orm/pglite/migrator";
import { pgliteClient, ensureLocalOrg, openDatabase } from "@zdocs/db-schema";
import { ensureWorkspaceDir, migrateLegacyDataDir } from "@zdocs/db-schema/data-dir";
import { getConfig } from "@zdocs/srv";
import { drizzle } from "drizzle-orm/pglite";

const migrationsFolder = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../../../packages/db-schema/migrations"
);

/**
 * Open the watch folder's own database (closing any open one), apply
 * migrations (generated by `npm run db:generate` from the zdocs schema) and
 * create the local org, root folder and system document types.
 */
export async function initDatabase(watchDir: string | null = getConfig().watchDir) {
  migrateLegacyDataDir(watchDir);
  const { dir, isNew } = ensureWorkspaceDir(watchDir);
  await openDatabase(dir);

  // Extensions used by zdocs' search index (trigram) and future vector search
  await pgliteClient.exec("CREATE EXTENSION IF NOT EXISTS pg_trgm;");
  await pgliteClient.exec("CREATE EXTENSION IF NOT EXISTS vector;");

  await migrate(drizzle(pgliteClient), { migrationsFolder });

  const local = await ensureLocalOrg();
  return { ...local, workspaceDir: dir, isNewWorkspace: isNew };
}
