/**
 * Formula Schema Generator
 *
 * Generates auto-sum fields for numeric line item columns.
 * Sum fields are added to headerSchema during document type seeding.
 *
 * @module formula-schema
 */

import type {
  FieldDefinition,
  LineItemCollectionSchema,
  FormulaSum,
} from "@zdocs/types";

/**
 * Generate auto-sum fields for all numeric fields in line item schemas.
 *
 * For each numeric field (type: "number" or "currency") in line item collections,
 * generates a corresponding sum field to be added to headerSchema.
 *
 * Sum fields are hidden by default (all visibility flags set to false) and
 * serve as building blocks for Phase 2 code fields (validation, derived values).
 *
 * @param lineItemSchemas - The line item schemas from a document type
 * @returns Array of sum field definitions to add to headerSchema
 *
 * @example
 * // Input: Invoice line items with quantity, unitPrice, amount
 * // Output: items_quantity_sum, items_unitPrice_sum, items_amount_sum fields
 */
export function generateAutoSumFields(
  lineItemSchemas: Record<string, LineItemCollectionSchema> | null | undefined
): FieldDefinition[] {
  if (!lineItemSchemas) {
    return [];
  }

  const sumFields: FieldDefinition[] = [];

  // Iterate through each collection (e.g., "items", "transactions", "holdings")
  for (const [collectionKey, collection] of Object.entries(lineItemSchemas)) {
    if (!collection?.fields) {
      continue;
    }

    // Find numeric fields in this collection
    for (const field of collection.fields) {
      // Only generate sum fields for number and currency types
      if (field.type !== "number" && field.type !== "currency") {
        continue;
      }

      // Skip fields that are not AI-extractable (system fields like pageNumber)
      if (field.aiExtractable === false) {
        continue;
      }

      // Generate the sum field name: {collection}_{field}_sum
      const sumFieldName = `${collectionKey}_${field.name}_sum`;

      // Create the formula definition
      const formula: FormulaSum = {
        fieldPath: `${collectionKey}.${field.name}`,
        fieldType: field.type as "number" | "currency",
      };

      // For currency fields, set the currency field path
      if (field.type === "currency") {
        if (field.currencyField) {
          formula.currencyFieldPath = `${collectionKey}.${field.currencyField}`;
        } else {
          formula.currencyFieldPath = "header.currency";
        }
      }

      // Create the sum field definition
      const sumField: FieldDefinition = {
        name: sumFieldName,
        type: "sum",
        displayName: `Sum of ${collection.displayName || collectionKey} ${
          field.displayName || field.name
        }`,
        hidden: true,
        description: `Auto-generated sum of ${
          field.displayName || field.name
        } from ${collection.displayName || collectionKey}`,
        // All visibility flags set to false - hidden building blocks
        searchable: false,
        isImportant: false,
        aiExtractable: false, // System-computed, not AI
        formula,
      };

      sumFields.push(sumField);
    }
  }

  return sumFields;
}

/**
 * Check if a field is an auto-generated sum field.
 *
 * Auto-generated sum fields follow the pattern: {collection}_{field}_sum
 *
 * @param field - The field definition to check
 * @returns true if this is an auto-generated sum field
 */
export function isAutoGeneratedSumField(field: FieldDefinition): boolean {
  return field.type === "sum";
}

/**
 * Merge auto-generated sum fields into header schema.
 *
 * - Existing sum fields with the same name are preserved (user customizations)
 * - New sum fields are appended
 * - Non-sum fields are not affected
 *
 * @param existingHeaderSchema - Current header schema
 * @param autoSumFields - Generated sum fields from generateAutoSumFields()
 * @returns Merged header schema with sum fields
 */
export function mergeAutoSumFields(
  existingHeaderSchema: FieldDefinition[],
  autoSumFields: FieldDefinition[]
): FieldDefinition[] {
  // Get names of existing fields
  const existingFieldNames = new Set(existingHeaderSchema.map((f) => f.name));

  // Filter out sum fields that already exist
  const newSumFields = autoSumFields.filter(
    (f) => !existingFieldNames.has(f.name)
  );

  // Append new sum fields to the end
  return [...existingHeaderSchema, ...newSumFields];
}
