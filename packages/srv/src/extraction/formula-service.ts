/**
 * Parameters for formula evaluation
 */
export interface EvaluateFormulasParams {
  documentType: DocumentTypeRecord;
  extractedData: {
    headerData: Record<string, unknown>;
    lineItems: Record<string, Record<string, unknown>[]>;
  };
  fileMetadata: FormulaFileMetadata;
  datasets?: Record<string, Record<string, unknown>[]>;
  onCodeLog?: (log: FormulaExecutionLog) => void;
}

/**
 * Evaluate all formula fields for a document.
 *
 * Execution order:
 * 1. Sum fields (simple aggregation)
 * 2. Code fields (user-defined JavaScript)
 * 3. AI fields (Phase 3 - not implemented yet)
 *
 * @param params - Parameters including document type, extracted data, file metadata, and datasets
 * @returns Enriched header data + line items with computed formula values + notifications
 */
export async function evaluateFormulas(
  params: EvaluateFormulasParams
): Promise<FormulaResult> {
  const {
    documentType,
    extractedData,
    fileMetadata,
    datasets = {},
    onCodeLog,
  } = params;
  const notifications: FormulaNotification[] = [];

  // Create mutable copies of data
  const headerData = { ...extractedData.headerData };
  const lineItems: Record<string, Record<string, unknown>[]> = {};

  // Deep copy line items to avoid mutating original
  for (const [key, items] of Object.entries(extractedData.lineItems || {})) {
    lineItems[key] = items.map((item) => ({ ...item }));
  }

  // Create context for formula evaluation
  const context: FormulaContext = {
    header: headerData,
    lineItems,
    file: fileMetadata,
  };

  // Get schemas
  const headerSchema = documentType.headerSchema as FieldDefinition[];
  const lineItemSchemas = documentType.lineItemSchemas as Record<
    string,
    LineItemCollectionSchema
  > | null;

  // ═══════════════════════════════════════════════════════════════════════════
  // Phase 1: Evaluate sum fields (header only)
  // ═══════════════════════════════════════════════════════════════════════════
  const sumFields = headerSchema.filter((f) => f.type === "sum");

  for (const field of sumFields) {
    try {
      const value = evaluateSumField(field, context);
      headerData[field.name] = value;
      // Update context.header so subsequent formulas see the computed value
      context.header[field.name] = value;
    } catch (error) {
      const errorMessage =
        error instanceof Error ? error.message : "Unknown error";
      notifications.push({
        level: "error",
        message: `Failed to evaluate sum field "${field.name}": ${errorMessage}`,
        formulaField: field.name,
      });
    }
  }

  // ═══════════════════════════════════════════════════════════════════════════
  // Phase 2: Evaluate code fields
  // ═══════════════════════════════════════════════════════════════════════════

  // 2a. Header code fields (execute once per document)
  const headerCodeFields = headerSchema.filter((f) => f.type === "code");

  for (const field of headerCodeFields) {
    try {
      const result = await evaluateCodeField(
        field,
        context,
        null, // collectionKey
        null, // collectionIndex
        datasets,
        (log) => {
          onCodeLog?.({
            level: log.level,
            message: formatLogMessage(log.message, log.meta),
            formulaField: field.name,
            fieldPath: `header.${field.name}`,
          });
        }
      );

      // Apply result to the field itself
      if (result.result !== undefined) {
        headerData[field.name] = result.result;
        context.header[field.name] = result.result;
      }

      // Apply additional mutations from tx object
      if (result.txResult) {
        applyTxMutations(
          result.txResult,
          headerData,
          lineItems,
          context,
          notifications,
          field.name
        );
      } else if (result.notification) {
        // Legacy: notification without full txResult
        notifications.push({
          ...result.notification,
          formulaField: field.name,
        });
      }
    } catch (error) {
      const errorMessage =
        error instanceof Error ? error.message : "Unknown error";
      notifications.push({
        level: "error",
        message: `Failed to evaluate code field "${field.name}": ${errorMessage}`,
        formulaField: field.name,
      });
    }
  }

  // 2b. Line item code fields (execute for each item in each collection)
  if (lineItemSchemas) {
    for (const [collectionKey, collectionSchema] of Object.entries(
      lineItemSchemas
    )) {
      const codeFields = collectionSchema.fields.filter(
        (f: FieldDefinition) => f.type === "code"
      );

      if (codeFields.length === 0) continue;

      const items = lineItems[collectionKey] || [];

      for (let index = 0; index < items.length; index++) {
        for (const field of codeFields) {
          try {
            const result = await evaluateCodeField(
              field,
              context,
              collectionKey,
              index,
              datasets,
              (log) => {
                onCodeLog?.({
                  level: log.level,
                  message: formatLogMessage(log.message, log.meta),
                  formulaField: field.name,
                  fieldPath: `${collectionKey}[${index}].${field.name}`,
                });
              }
            );

            // Apply result to the field itself
            if (result.result !== undefined) {
              lineItems[collectionKey][index][field.name] = result.result;
              // Update context so subsequent formulas see the computed value
              context.lineItems[collectionKey][index][field.name] =
                result.result;
            }

            // Apply additional mutations from tx object
            if (result.txResult) {
              applyTxMutations(
                result.txResult,
                headerData,
                lineItems,
                context,
                notifications,
                field.name
              );
            } else if (result.notification) {
              // Legacy: notification without full txResult
              notifications.push({
                ...result.notification,
                formulaField: field.name,
              });
            }
          } catch (error) {
            const errorMessage =
              error instanceof Error ? error.message : "Unknown error";
            notifications.push({
              level: "error",
              message: `Failed to evaluate code field "${field.name}" for ${collectionKey}[${index}]: ${errorMessage}`,
              formulaField: field.name,
              fieldPath: `${collectionKey}[${index}].${field.name}`,
            });
          }
        }
      }
    }
  }

  return {
    headerData,
    lineItems,
    notifications,
  };
}

// ═══════════════════════════════════════════════════════════════════════════════
// SUM FIELD EVALUATION
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * Evaluate a sum field - aggregate a numeric column from line items.
 *
 * @param field - The sum field definition
 * @param context - The formula context with header and lineItems data
 * @returns The computed sum value, or null if collection doesn't exist
 */
export function evaluateSumField(
  field: FieldDefinition,
  context: FormulaContext
): number | null {
  const formula = field.formula as FormulaSum;

  if (!formula || field.type !== "sum") {
    return null;
  }

  // Parse fieldPath: "items.amount" -> ["items", "amount"]
  const [collectionKey, fieldName] = formula.fieldPath.split(".");

  if (!collectionKey || !fieldName) {
    console.warn(
      `Invalid fieldPath in sum formula: ${formula.fieldPath}. Expected format: "collection.field"`
    );
    return null;
  }

  // Get the collection from lineItems
  const collection = context.lineItems[collectionKey];

  if (!collection || !Array.isArray(collection)) {
    // Collection doesn't exist or is empty - return 0 (not null)
    // This is intentional: sum of nothing is 0
    return 0;
  }

  // Sum the field values
  let sum = 0;
  for (const item of collection) {
    const value = (item as Record<string, unknown>)[fieldName];
    if (typeof value === "number" && !isNaN(value)) {
      sum += value;
    }
    // Non-numeric values are skipped (treated as 0)
  }

  // Round to 2 decimal places to avoid floating point issues
  return Math.round(sum * 100) / 100;
}

/**
 * Get the currency code for a sum field (Phase 1 - basic implementation).
 *
 * @param field - The sum field definition
 * @param context - The formula context
 * @returns Currency code from header, or null
 */
export function getCurrencyForSumField(
  field: FieldDefinition,
  context: FormulaContext,
  index?: number
): string | null {
  const formula = field.formula as FormulaSum;

  if (formula?.fieldType !== "currency" || !formula.currencyFieldPath) {
    return null;
  }

  // Parse currencyFieldPath: "header.currency" -> currency value
  const [location, fieldName] = formula.currencyFieldPath.split(".");

  if (location === "header" && fieldName) {
    const value = context.header[fieldName];
    return typeof value === "string" ? value : null;
  } else if (context.lineItems[location] && fieldName) {
    const value = context.lineItems[location][index ?? 0][fieldName];
    return typeof value === "string" ? value : null;
  }

  // For line item currency (mixed currencies) - not fully supported yet
  // Would need validation that all items have the same currency
  return null;
}

