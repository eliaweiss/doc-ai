/**
 * Evaluate a code field using TxScript-like API.
 *
 * The formula code receives a single `tx` parameter which provides:
 * - Read operations: tx.getField(), tx.getCurrentLineItem(), etc.
 * - Write operations: tx.setResult(), tx.setField(), tx.setCurrentLineField()
 * - Messaging: tx.addMessage()
 * - Dataset access: tx.dataset.lookup(), tx.dataset.getAll()
 * - HTTP access: tx.http.request()
 *
 * @param field - The code field definition
 * @param context - The formula context with header, lineItems, and file data
 * @param collectionKey - Current collection name, or null for header formulas
 * @param collectionIndex - Current item index, or null for header formulas
 * @param datasets - Loaded datasets keyed by type name
 * @returns The code field result with full tx mutations
 */
export async function evaluateCodeField(
  field: FieldDefinition,
  context: FormulaContext,
  collectionKey: string | null,
  collectionIndex: number | null,
  datasets: Record<string, Record<string, unknown>[]>,
  onLog?: (log: {
    level: "debug" | "info" | "warn" | "error";
    message: string;
    meta?: Record<string, unknown>;
  }) => void
): Promise<CodeFieldReturn> {
  const formula = field.formula as FormulaCode;

  if (!formula || field.type !== "code" || !formula.code) {
    return { result: null };
  }

  // doc-ai: code fields run unsandboxed with full Node access (see security-notes.md).
  // Until the schema review + approval flow exists they are off unless explicitly enabled.
  if (process.env.DOC_AI_ALLOW_CODE_FORMULAS !== "true") {
    onLog?.({
      level: "warn",
      message: `Code field "${field.name}" skipped: code formulas are disabled (DOC_AI_ALLOW_CODE_FORMULAS)`,
    });
    return { result: null };
  }

  try {
    // Create TxFormulaContext from FormulaContext
    const txContext: TxFormulaContext = {
      header: context.header,
      lineItems: context.lineItems,
      file: context.file,
    };

    // Create tx capability object (TxScript style)
    const tx = new Tx(
      txContext,
      collectionKey,
      collectionIndex,
      datasets,
      {},
      onLog
    );

    const consoleProxy = {
      debug: (...args: unknown[]) => {
        const message = stringifyLogArgs(args);
        onLog?.({ level: "debug", message });
        console.debug(...args);
      },
      info: (...args: unknown[]) => {
        const message = stringifyLogArgs(args);
        onLog?.({ level: "info", message });
        console.info(...args);
      },
      log: (...args: unknown[]) => {
        const message = stringifyLogArgs(args);
        onLog?.({ level: "info", message });
        console.log(...args);
      },
      warn: (...args: unknown[]) => {
        const message = stringifyLogArgs(args);
        onLog?.({ level: "warn", message });
        console.warn(...args);
      },
      error: (...args: unknown[]) => {
        const message = stringifyLogArgs(args);
        onLog?.({ level: "error", message });
        console.error(...args);
      },
    };

    // Create an async function that receives tx and a scoped console.
    const AsyncFunction = Object.getPrototypeOf(
      async function () { }
    ).constructor;

    const fn = new AsyncFunction(
      "tx",
      "console",
      `"use strict";\n${formula.code}`
    );

    // Execute with timeout protection
    const timeoutMs = TX_DEFAULT_LIMITS.executionTimeoutMs; // 5 minutes
    let timeoutId: NodeJS.Timeout | null = null;
    const timeoutPromise = new Promise<never>((_, reject) => {
      timeoutId = setTimeout(
        () => reject(new Error(`Code field execution timed out after ${timeoutMs}ms`)),
        timeoutMs
      );
    });

    try {
      await Promise.race([fn(tx, consoleProxy), timeoutPromise]);
    } finally {
      if (timeoutId) {
        clearTimeout(timeoutId);
      }
    }

    // Get all mutations from tx
    const txResult = tx.getExecutionResult();

    return {
      result: txResult.result,
      notification: txResult.messages[0], // First notification for compatibility
      txResult,
    };
  } catch (error) {
    const errorMessage =
      error instanceof Error ? error.message : "Unknown error";

    // Special handling for validation and rate limit errors
    const isValidationError = error instanceof TxValidationError;
    const isRateLimitError = error instanceof TxRateLimitError;

    const errorType = isRateLimitError
      ? "Rate limit error"
      : isValidationError
        ? "Validation error"
        : "Code execution error";

    // Return error as notification
    return {
      result: null,
      notification: {
        level: "error",
        message: `${errorType}: ${errorMessage}`,
        fieldPath: collectionKey
          ? `${collectionKey}[${collectionIndex}].${field.name}`
          : `header.${field.name}`,
      },
    };
  }
}

function formatLogMessage(
  message: string,
  meta?: Record<string, unknown>
): string {
  if (!meta || Object.keys(meta).length === 0) return message;
  try {
    return `${message} ${JSON.stringify(meta)}`;
  } catch {
    return message;
  }
}

function stringifyLogArgs(args: unknown[]): string {
  if (args.length === 0) return "";
  return args.map((arg) => stringifyLogArg(arg)).join(" ");
}

function stringifyLogArg(value: unknown): string {
  if (typeof value === "string") return value;
  try {
    return JSON.stringify(value);
  } catch {
    return String(value);
  }
}

