/**
 * Get all formula fields from a schema.
 *
 * @param schema - Array of field definitions
 * @returns Fields that have a formula property
 */
export function getFormulaFields(schema: FieldDefinition[]): FieldDefinition[] {
  return schema.filter((f) => f.formula !== undefined);
}

/**
 * Check if a document type has any formula fields.
 *
 * @param documentType - The document type record
 * @returns true if any fields have formulas defined
 */
export function hasFormulaFields(documentType: DocumentTypeRecord): boolean {
  const headerSchema = documentType.headerSchema as FieldDefinition[];
  return headerSchema.some((f) => f.formula !== undefined);
}
