/**
 * Formula Service
 *
 * Evaluates formula fields (sum, code) after AI extraction.
 * Formulas run in deterministic order: sum → code
 *
 * Uses TxScript-like API where formula code receives a `tx` capability object
 * that mediates all reads, writes, and side effects.
 *
 * @module formula-service
 */

import type {
  DocumentTypeRecord,
  FieldDefinition,
  FormulaSum,
  FormulaCode,
  LineItemCollectionSchema,
  TxResult,
  TxFormulaContext,
} from "@zdocs/types";

import { TX_DEFAULT_LIMITS } from "@zdocs/types";

import { Tx, TxValidationError, TxRateLimitError } from "./tx-capability";

// ═══════════════════════════════════════════════════════════════════════════════
// TYPES
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * Notification generated by formula evaluation
 */
export interface FormulaNotification {
  level: "info" | "warning" | "error";
  message: string;
  fieldPath?: string; // e.g., "header.total", "items[2].amount"
  formulaField?: string; // Which formula field generated this notification
}

/**
 * File metadata available in formula context
 * @deprecated Use TxFileMetadata from @zdocs/types
 */
export interface FormulaFileMetadata {
  id: string;
  fileName: string;
  uploadDate: string; // ISO date
  fileType: string; // MIME type
  status: string; // extractionStatus
}

/**
 * Input structure for formula evaluation
 * @deprecated Use TxFormulaContext from @zdocs/types
 */
export interface FormulaContext {
  header: Record<string, unknown>;
  lineItems: Record<string, Record<string, unknown>[]>;
  file: FormulaFileMetadata;
}

/**
 * Result of formula evaluation
 */
export interface FormulaResult {
  headerData: Record<string, unknown>;
  lineItems: Record<string, Record<string, unknown>[]>;
  notifications: FormulaNotification[];
}

export interface FormulaExecutionLog {
  level: "debug" | "info" | "warn" | "error";
  message: string;
  formulaField: string;
  fieldPath: string;
}

/**
 * Return structure from code field execution (internal use)
 */
export interface CodeFieldReturn {
  result: unknown;
  notification?: FormulaNotification;
  /** Full tx result with all mutations */
  txResult?: TxResult;
}

