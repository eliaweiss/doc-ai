// TX MUTATION APPLICATION
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * Apply mutations from a TxResult to the document data.
 * This includes header field changes, line item field changes, and notifications.
 *
 * @param txResult - The tx execution result containing all mutations
 * @param headerData - Mutable header data to update
 * @param lineItems - Mutable line items to update
 * @param context - The formula context to keep in sync
 * @param notifications - Array to append notifications to
 * @param formulaField - Name of the formula field (for notification attribution)
 */
function applyTxMutations(
  txResult: TxResult,
  headerData: Record<string, unknown>,
  lineItems: Record<string, Record<string, unknown>[]>,
  context: FormulaContext,
  notifications: FormulaNotification[],
  formulaField: string
): void {
  // Apply header field changes
  for (const [fieldName, value] of Object.entries(txResult.fieldChanges)) {
    headerData[fieldName] = value;
    context.header[fieldName] = value;
  }

  // Apply line item field changes
  for (const [collection, indexChanges] of Object.entries(
    txResult.lineFieldChanges
  )) {
    for (const [idxStr, fieldChanges] of Object.entries(indexChanges)) {
      const idx = parseInt(idxStr, 10);
      for (const [fieldName, value] of Object.entries(fieldChanges)) {
        if (lineItems[collection]?.[idx]) {
          lineItems[collection][idx][fieldName] = value;
        }
        if (context.lineItems[collection]?.[idx]) {
          context.lineItems[collection][idx][fieldName] = value;
        }
      }
    }
  }

  // Add all messages from tx as notifications
  for (const message of txResult.messages) {
    notifications.push({
      level: message.level,
      message: message.message,
      fieldPath: message.fieldPath,
      formulaField,
    });
  }
}

