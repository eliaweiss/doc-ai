// Writes index.html from assets/voice/timing.json: one host per scene, the
// narration audio, the three.js world behind them, and window.VO (every
// sentence's start and end, in scene time) for the scenes to animate on.
//
// Run after scripts/tts.py, whenever the narration changes: node scripts/build.mjs
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const timing = JSON.parse(fs.readFileSync(path.join(ROOT, "assets/voice/timing.json"), "utf8"));

const LEAD = 0.6; // picture before the voice starts in each scene
const TAIL = 0.6; // after the last sentence, before the next scene
const END_HOLD = 2.4; // the last line stays on screen

let t = 0;
const scenes = timing.scenes.map((scene, i) => {
  const last = i === timing.scenes.length - 1;
  const duration = +(LEAD + scene.duration + (last ? END_HOLD : TAIL)).toFixed(3);
  const entry = {
    id: scene.id,
    start: +t.toFixed(3),
    duration,
    lead: LEAD,
    audio: scene.audio,
    voice: scene.duration,
    sentences: scene.sentences.map((s) => ({ text: s.text, start: +(LEAD + s.start).toFixed(3), end: +(LEAD + s.end).toFixed(3) })),
  };
  t += duration;
  return entry;
});
const total = +t.toFixed(3);

const hosts = scenes
  .map(
    (s, i) => `      <div id="${s.id}" data-composition-id="${s.id}" data-composition-src="compositions/${s.id}.html"
           data-start="${s.start}" data-duration="${s.duration}" data-track-index="${i + 2}"
           data-width="1920" data-height="1080"></div>`
  )
  .join("\n");
const audio = scenes
  .map(
    (s, i) => `      <audio id="vo-${s.id}" src="${s.audio}" data-start="${(s.start + s.lead).toFixed(3)}" data-duration="${s.voice}" data-volume="1" data-track-index="${20 + i}"></audio>`
  )
  .join("\n");

const html = `<!doctype html>
<!-- Generated by scripts/build.mjs from assets/voice/timing.json. Edit the scenes in compositions/, not this file. -->
<html lang="en" data-resolution="landscape">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1920, height=1080" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <style>
      :root {
        --ground: #ccc9db;
        --ink: #1b1a1f;
        --ink-soft: rgba(27, 26, 31, 0.16);
        --clay: #c96442;
        --clay-text: #9b3d20;
        --peach: #f3d9c8;
        --paper: #fbf9f5;
        --font-display: "EB Garamond", serif;
        --font-ui: "Inter", sans-serif;
      }
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { width: 1920px; height: 1080px; overflow: hidden; background: var(--ground); }
      #root { position: relative; width: 1920px; height: 1080px; overflow: hidden; background: var(--ground); }

      /* Shared by the scenes (compositions/*.html) */
      .scene { position: absolute; inset: 0; font-family: var(--font-display); color: var(--ink); }
      .abs { position: absolute; }
      .center { left: 0; right: 0; text-align: center; }
      .serif { font-family: var(--font-display); font-weight: 400; letter-spacing: -0.015em; line-height: 1.05; }
      .sans { font-family: var(--font-ui); }
      .huge { font-size: 230px; letter-spacing: -0.035em; }
      .h1 { font-size: 96px; }
      .h2 { font-size: 72px; }
      .h3 { font-size: 54px; }
      .kicker { font-family: var(--font-ui); font-size: 30px; font-weight: 600; letter-spacing: 0.14em; text-transform: uppercase; color: var(--clay-text); }
      .accent { color: var(--clay-text); }
      .w { display: inline-block; }
      .chip { display: inline-block; padding: 18px 34px; border-radius: 999px; background: var(--paper);
              font-family: var(--font-ui); font-size: 34px; font-weight: 600; color: var(--ink);
              box-shadow: 0 10px 30px rgba(40, 35, 70, 0.14); }
      .card { border-radius: 22px; overflow: hidden; background: var(--paper);
              box-shadow: 0 30px 80px rgba(40, 35, 70, 0.28), 0 0 0 1px rgba(27, 26, 31, 0.08); }
      .card img { display: block; width: 100%; height: auto; }
      .bubble { display: inline-block; max-width: 1100px; padding: 26px 38px; border-radius: 34px 34px 10px 34px;
                background: var(--peach); font-family: var(--font-ui); font-size: 40px; font-weight: 500;
                color: var(--ink); box-shadow: 0 12px 34px rgba(40, 35, 70, 0.14); }
      .num { font-family: var(--font-ui); font-weight: 700; color: var(--clay); }
    </style>
    <script>
      // Narration timing, in each scene's own time (seconds from the scene's start).
      window.VO = ${JSON.stringify({ total, scenes: Object.fromEntries(scenes.map((s) => [s.id, s])) })};

      // Helpers the scenes share. Everything here runs before the scenes build
      // their timelines, and is a pure function of the timing above.
      window.DOC = {
        /** Start and end of sentence i of a scene, in scene time. */
        at(scene, i) { return window.VO.scenes[scene].sentences[i].start; },
        end(scene, i) { return window.VO.scenes[scene].sentences[i].end; },
        /** When each word of a sentence is spoken, spread by length over the sentence. */
        wordTimes(scene, i, words) {
          const s = window.VO.scenes[scene].sentences[i];
          const weights = words.map((w) => w.length + 2);
          const sum = weights.reduce((a, b) => a + b, 0);
          let t = s.start;
          return weights.map((w) => { const at = t; t += ((s.end - s.start) * w) / sum; return at; });
        },
        /**
         * Wrap each word of el in a span, keeping inner markup (an .accent
         * span keeps its colour). Returns the word spans in reading order.
         */
        split(el) {
          if (el.__words) return el.__words;
          const spans = [];
          const walk = (node) => {
            for (const child of [...node.childNodes]) {
              if (child.nodeType === 1) { walk(child); continue; }
              if (child.nodeType !== 3) continue;
              const frag = document.createDocumentFragment();
              child.textContent.split(/(\\s+)/).forEach((part) => {
                if (!part) return;
                if (/^\\s+$/.test(part)) { frag.appendChild(document.createTextNode(part)); return; }
                const span = document.createElement("span");
                span.className = "w";
                span.textContent = part;
                frag.appendChild(span);
                spans.push(span);
              });
              child.replaceWith(frag);
            }
          };
          walk(el);
          el.__words = spans;
          return spans;
        },
        /** Darken el's words from light gray to their own colour at the given times. */
        darken(tl, el, times) {
          window.DOC.split(el).forEach((span, k) => {
            const accent = !!span.closest(".accent");
            tl.fromTo(span,
              { color: accent ? "rgba(155,61,32,0.24)" : "rgba(27,26,31,0.16)" },
              { color: accent ? "#9b3d20" : "#1b1a1f", duration: 0.14, ease: "none" },
              times[Math.min(k, times.length - 1)]);
          });
        },
        /** Darken el's words as sentence i of the scene speaks them. */
        speak(tl, el, scene, i) {
          const words = window.DOC.split(el).map((s) => s.textContent);
          const times = window.DOC.wordTimes(scene, i, words);
          window.DOC.darken(tl, el, times);
          return times;
        },
        /**
         * Darken el's words one by one, spread from t0 to t1: for an
         * on-screen line that condenses what the voice says.
         */
        words(tl, el, t0, t1) {
          const n = window.DOC.split(el).length;
          const step = n > 1 ? (t1 - t0) / (n - 1) : 0;
          window.DOC.darken(tl, el, Array.from({ length: n }, (_, k) => t0 + k * step));
        },
        /** Arrive: opacity 0 -> 1 with the blur clearing (and an optional rise). */
        blurIn(tl, el, t, o = {}) {
          tl.fromTo(el,
            { opacity: 0, filter: "blur(" + (o.blur ?? 10) + "px)", y: o.y ?? 0, scale: o.scale ?? 1 },
            { opacity: 1, filter: "blur(0px)", y: 0, scale: 1, duration: o.duration ?? 0.5, ease: o.ease ?? "expo.out" }, t);
        },
        /** Leave: one quick blur-out. */
        blurOut(tl, el, t, o = {}) {
          tl.to(el, { opacity: 0, filter: "blur(" + (o.blur ?? 10) + "px)", y: o.y ?? 0, scale: o.scale ?? 1,
            duration: o.duration ?? 0.25, ease: "power3.in" }, t);
        },
      };
    </script>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="${total}"
         data-width="1920" data-height="1080">
      <div id="world" data-composition-id="world" data-composition-src="compositions/world.html"
           data-start="0" data-duration="${total}" data-track-index="1"
           data-width="1920" data-height="1080"></div>
${hosts}
${audio}
    </div>
    <script>
      window.__timelines = window.__timelines || {};
      window.__timelines["main"] = gsap.timeline({ paused: true });
    </script>
  </body>
</html>
`;

fs.writeFileSync(path.join(ROOT, "index.html"), html);
// The world's canvas lasts the whole film
const worldPath = path.join(ROOT, "compositions/world.html");
fs.writeFileSync(worldPath, fs.readFileSync(worldPath, "utf8")
  .replace(/(id="world-canvas"[^>]*data-duration=")[\d.]+/, `$1${total}`));
console.log(`[build] index.html: ${scenes.length} scenes, ${total.toFixed(1)}s`);
for (const s of scenes) console.log(`  ${s.id.padEnd(9)} ${s.start.toFixed(2)}s  +${s.duration.toFixed(2)}s  (${s.sentences.length} sentences)`);
